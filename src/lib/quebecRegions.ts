// Obtenir toutes les villes d'une ou plusieurs régions
export const getCitiesFromRegions = (regionCodes: string[]): string[] => {
  const cities = new Set<string>();
  
  regionCodes.forEach(code => {
    const region = QUEBEC_REGIONS.find(r => r.code === code);
    if (region) {
      region.cities.forEach(city => cities.add(city));
    }
  });
  
  return Array.from(cities).sort();
};

// Obtenir toutes les villes de toutes les régions
export const getAllCities = (): string[] => {
  const cities = new Set<string>();
  
  QUEBEC_REGIONS.forEach(region => {
    region.cities.forEach(city => cities.add(city));
  });
  
  return Array.from(cities).sort();
};
